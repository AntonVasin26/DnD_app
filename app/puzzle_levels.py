"""
Каноничные, жёстко заданные уровни головоломки.

ВАЖНО (см. PROJECT_CONTEXT.md, пункт 15 плана): раньше здесь не было единого
источника правды — test_engine_butterfly.py использовал СТАРУЮ 2-точечную
версию диагоналей (A-E, B-D, target=6), а фронтенд-прототип (index.html)
уже давно жил на 3-точечной версии (A-C-E, B-C-D, target=9). Теперь уровень
описан здесь ОДИН раз, с геометрией, совпадающей с фронтендом, и именно
этот объект используется и в WebSocket-эндпоинте на сервере, и в ручном
тесте (test_engine_butterfly.py).

ИМЕНОВАНИЕ (по просьбе пользователя): называем уровни "созвездиями", а не
"уровнями" — id (`"butterfly"`/`"pentagon"`/`"square"`) остаются техническими
и НЕ меняются (используются в коде и в WebSocket-протоколе как level_id),
меняется только `name` — то, что видит игрок. "Созвездие Бабочки" назвал сам
пользователь; "Созвездие Скорпиона" (для PENTAGON_LEVEL) и "Созвездие
Тельца" (для SQUARE_LEVEL) — предложены Claude по просьбе "остальное пока
придумай" и легко меняются, если пользователь захочет другие названия.
"""

from app.puzzle_models import Level, Point, Shape, Line

BUTTERFLY_LEVEL = Level(
    id="butterfly",
    name="Созвездие Бабочки",
    points=[
        Point(id="A", value=1),
        Point(id="B", value=2),
        Point(id="C", value=3),
        Point(id="D", value=4),
        Point(id="E", value=5),
    ],
    shapes=[
        # Порядок обхода по кругу должен совпадать с направлением, которое
        # фронтенд считает "по часовой стрелке" (см. VERTEX_COORDS и
        # computeRotatedValues в index.html): A -> C -> D -> (снова A).
        Shape(id="left", point_ids=["A", "C", "D"]),
        # B -> E -> C -> (снова B).
        Shape(id="right", point_ids=["B", "E", "C"]),
    ],
    lines=[
        # Диагонали идут ЧЕРЕЗ общую вершину C, а не мимо неё — это и есть
        # актуальная (3-точечная) версия, на которую давно перешёл фронтенд.
        Line(id="diag1", point_ids=["A", "C", "E"], target=9),  # 1+3+5=9 ✓ на старте
        Line(id="diag2", point_ids=["B", "C", "D"], target=9),  # 2+3+4=9 ✓ на старте
    ],
)

# Второй уровень (в разработке, см. PROJECT_CONTEXT.md — планировали вместе
# с пользователем): пятиугольник A-B-C-D-E + два треугольника, приклеенных
# РЁБРАМИ (не вершинами!) к сторонам 1 (A-B) и 3 (C-D) пятиугольника.
# Геометрия (пронумеровано от вершины A по часовой стрелке):
#   A(верх) -> B(право-верх) -> C(право-низ) -> D(лево-низ) -> E(лево-верх) -> снова A
#   треугольник "top_wedge"    : A, B, F (F — новая вершина, апекс наружу от стороны 1)
#   треугольник "bottom_wedge" : C, D, G (G — новая вершина, апекс наружу от стороны 3)
# Итого 7 точек, 3 фигуры. У треугольников ПО ДВЕ точки общие с
# пятиугольником (сама грань), а не одна — более тесная связь фигур,
# чем в BUTTERFLY_LEVEL.
#
# Значения по умолчанию — просто по алфавиту (1..7), как и в
# BUTTERFLY_LEVEL, значит на старте (до scramble()) уровень решён.
# Линии — из обсуждения с пользователем:
#   line1: F-B-C-G (4 точки), target = 6+2+3+7 = 18
#   line2: F-A-E   (3 точки), target = 6+1+5   = 12
#   line3: G-D-E   (3 точки), target = 7+4+5   = 16
# Точка E участвует СРАЗУ в line2 и line3 — так же, как раньше C была общей
# для diag1 и diag2: поворот пятиугольника, меняющий E, задевает оба условия
# сразу.
PENTAGON_LEVEL = Level(
    id="pentagon",
    name="Созвездие Скорпиона",
    points=[
        Point(id="A", value=1),
        Point(id="B", value=2),
        Point(id="C", value=3),
        Point(id="D", value=4),
        Point(id="E", value=5),
        Point(id="F", value=6),
        Point(id="G", value=7),
    ],
    shapes=[
        # Обход по кругу в геометрическом порядке (по часовой стрелке от A) —
        # тот же принцип, что и в BUTTERFLY_LEVEL: порядок в point_ids ДОЛЖЕН
        # совпадать с реальным обходом вершин фигуры на экране, иначе при
        # подключении фронтенда числа поедут не в ту сторону.
        Shape(id="pentagon", point_ids=["A", "B", "C", "D", "E"]),
        Shape(id="top_wedge", point_ids=["A", "B", "F"]),
        Shape(id="bottom_wedge", point_ids=["C", "D", "G"]),
    ],
    lines=[
        Line(id="line1", point_ids=["F", "B", "C", "G"], target=18),  # 6+2+3+7=18 ✓
        Line(id="line2", point_ids=["F", "A", "E"], target=12),       # 6+1+5=12 ✓
        Line(id="line3", point_ids=["G", "D", "E"], target=16),       # 7+4+5=16 ✓
    ],
)

# Третий уровень: квадрат A-B-C-D + два треугольника, приклеенных ВЕРШИНАМИ
# (не гранями, как у пятиугольника!) — ближе по духу к самой первой
# "бабочке". Геометрия придумана вместе с пользователем в чате, подтверждена
# черновым SVG-наброском (level3_square_sketch.html — не часть приложения):
#   Квадрат касается треугольника "wedge_left" РОВНО В ОДНОЙ точке — своей
#   вершине A ("вершина 1" квадрата), и треугольника "wedge_right" — тоже
#   ровно в одной точке, вершине B ("вершина 2"). Сами треугольники между
#   собой ТОЖЕ соединены одной общей вершиной E — точно как левый и правый
#   треугольник в BUTTERFLY_LEVEL были соединены точкой C. "Бантик" из двух
#   треугольников как бы подвешен за свои внешние вершины (A, B) к двум
#   соседним углам квадрата, а его собственная общая точка E ни с чем,
#   кроме самих треугольников, не связана.
#
# Итого 7 точек (A..G), как и в PENTAGON_LEVEL, но другая геометрия и
# другая структура связей: quadrilateral=[A,B,C,D] (4-цикл — единственная
# фигура во всём проекте с 4 точками, поворот на 90°, никакого спецкода это
# не потребовало — stepDegrees на фронтенде и rotate() на бэкенде уже
# полностью общие), wedge_left=[A,F,E], wedge_right=[B,E,G] (оба 3-цикла).
#
# Значения по умолчанию — по алфавиту (1..7), как и раньше, уровень решён
# до scramble(). Линии — из обсуждения с пользователем ("пусть будет сумма
# F-A-D и G-B-C"), ТОЛЬКО ДВЕ линии (в отличие от BUTTERFLY_LEVEL и
# PENTAGON_LEVEL, где каждая точка входила хотя бы в одну линию) —
# сознательное решение пользователя, точка E НИ В ОДНУ линию не входит:
# она по-прежнему двигается при повороте любого из треугольников (входит в
# обе фигуры), но её конкретное значение никогда не проверяется условием
# суммы. Уровень от этого не становится некорректным — просто изменяется
# структура/сложность головоломки.
#   line1: F-A-D (3 точки), target = 6+1+4 = 11
#   line2: G-B-C (3 точки), target = 7+2+3 = 12
SQUARE_LEVEL = Level(
    id="square",
    name="Созвездие Тельца",
    points=[
        Point(id="A", value=1),
        Point(id="B", value=2),
        Point(id="C", value=3),
        Point(id="D", value=4),
        Point(id="E", value=5),
        Point(id="F", value=6),
        Point(id="G", value=7),
    ],
    shapes=[
        # Обход по кругу по часовой стрелке (см. комментарий выше про
        # порядок point_ids): A(верх-лево) -> B(верх-право) ->
        # C(низ-право) -> D(низ-лево) -> снова A.
        Shape(id="quadrilateral", point_ids=["A", "B", "C", "D"]),
        # A(низ треугольника, общая с квадратом) -> F(своя, верх-лево) ->
        # E(общая с wedge_right) -> снова A.
        Shape(id="wedge_left", point_ids=["A", "F", "E"]),
        # B(низ треугольника, общая с квадратом) -> E(общая с wedge_left,
        # ТА ЖЕ точка) -> G(своя, верх-право) -> снова B.
        Shape(id="wedge_right", point_ids=["B", "E", "G"]),
    ],
    lines=[
        Line(id="line1", point_ids=["F", "A", "D"], target=11),  # 6+1+4=11 ✓
        Line(id="line2", point_ids=["G", "B", "C"], target=12),  # 7+2+3=12 ✓
    ],
)
