"""
Модели данных головоломки.

Ключевая идея: Point (точка) существует независимо от фигур.
Shape (фигура) и Line (линия) — это просто СПИСКИ ID точек.
Общие вершины между фигурами реализуются естественно: если два
разных Shape ссылаются на один и тот же point_id, они "делят" эту точку.
"""

from pydantic import BaseModel


class Point(BaseModel):
    """Одна вершина на поле — просто число с идентификатором."""
    id: str
    value: int


class Shape(BaseModel):
    """
    Многогранник. point_ids хранится ПО КРУГУ (в порядке обхода вершин) —
    это важно, именно порядок в этом списке определяет, как числа
    сдвигаются друг относительно друга при повороте.
    """
    id: str
    point_ids: list[str]


class Line(BaseModel):
    """
    "Прямая" для проверки условия. Пока поддерживаем только сумму,
    но оставляем поле operation, чтобы позже добавить произведение и т.д.
    без переделки структуры.
    """
    id: str
    point_ids: list[str]
    operation: str = "sum"
    target: int


class Level(BaseModel):
    """Шаблон одного уровня головоломки — статичные данные, не меняются во время игры."""
    id: str
    name: str
    points: list[Point]
    shapes: list[Shape]
    lines: list[Line]
